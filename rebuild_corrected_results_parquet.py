#!/usr/bin/env python3
"""
Convert corrected_accepted_results.csv to a lossless Parquet dataset.

Purpose
-------
The CSV is the machine-readable counterpart of the `corrected_results`
sheet generated by the revised robustness postprocessor. Excel truncates
very long N=100 edge_list_json cells at its per-cell character limit,
while the CSV preserves the complete JSON.

This script:
1. Reads corrected_accepted_results.csv directly.
2. Preserves all rows and all columns.
3. Does NOT rerun simulations.
4. Does NOT recalculate classifications.
5. Validates edge_list_json, initial_state_json, and final_state_json.
6. Writes corrected_results.parquet.
7. Performs a read-back validation.

Input:
    corrected_accepted_results.csv

Output:
    corrected_results.parquet
"""

from pathlib import Path
import argparse
import json
import pandas as pd


def validate_dataset(df: pd.DataFrame) -> None:
    """Validate the dataset without changing its contents."""

    required_columns = [
        "experiment",
        "condition",
        "network",
        "N",
        "case",
        "run_seed",
        "edge_list_json",
        "initial_state_json",
        "final_state_json",
        "outcome_class_revised",
        "deviates_from_analytical_share_benchmark",
    ]

    missing = [c for c in required_columns if c not in df.columns]
    if missing:
        raise ValueError(
            f"Missing required columns: {missing}"
        )

    problems = []

    # Validate every accepted case-level row.
    for idx, row in df.iterrows():

        try:
            n = int(row["N"])
            case = int(row["case"])
            run_seed = row["run_seed"]
        except Exception as exc:
            problems.append(
                (idx, "metadata", str(exc))
            )
            continue

        # ----------------------------------------------------------
        # edge_list_json
        # ----------------------------------------------------------
        try:
            edges = json.loads(row["edge_list_json"])

            if not isinstance(edges, list):
                raise ValueError(
                    "edge_list_json is not a JSON list"
                )

            # Compare with saved edge count when available.
            if "n_edges" in df.columns:
                saved_n_edges = int(row["n_edges"])

                if len(edges) != saved_n_edges:
                    raise ValueError(
                        f"JSON contains {len(edges)} edges, "
                        f"but n_edges={saved_n_edges}"
                    )

            # Validate each edge.
            for edge in edges:
                if (
                    not isinstance(edge, (list, tuple))
                    or len(edge) != 2
                ):
                    raise ValueError(
                        f"Invalid edge record: {edge}"
                    )

                u = int(edge[0])
                v = int(edge[1])

                if not (0 <= u < n and 0 <= v < n):
                    raise ValueError(
                        f"Edge {(u, v)} outside node range 0..{n-1}"
                    )

                if u == v:
                    raise ValueError(
                        f"Self-loop found: {(u, v)}"
                    )

        except Exception as exc:
            problems.append(
                (idx, run_seed, "edge_list_json", str(exc))
            )

        # ----------------------------------------------------------
        # initial_state_json / final_state_json
        # ----------------------------------------------------------
        for field in (
            "initial_state_json",
            "final_state_json",
        ):
            try:
                state = json.loads(row[field])

                if not isinstance(state, list):
                    raise ValueError(
                        f"{field} is not a JSON list"
                    )

                if len(state) != n:
                    raise ValueError(
                        f"{field} has length {len(state)}, "
                        f"expected N={n}"
                    )

                for value in state:
                    if int(value) not in (0, 1):
                        raise ValueError(
                            f"{field} contains strategy value "
                            f"{value}, expected 0 or 1"
                        )

            except Exception as exc:
                problems.append(
                    (idx, run_seed, field, str(exc))
                )

    if problems:
        preview = "\n".join(
            str(problem) for problem in problems[:20]
        )

        raise ValueError(
            "\nValidation failed.\n"
            "First problems:\n"
            f"{preview}"
        )


def main():

    parser = argparse.ArgumentParser(
        description=(
            "Convert corrected_accepted_results.csv "
            "to corrected_results.parquet."
        )
    )

    parser.add_argument(
        "--input",
        default="corrected_accepted_results.csv",
        help="Input CSV file."
    )

    parser.add_argument(
        "--output",
        default="corrected_results.parquet",
        help="Output Parquet file."
    )

    args = parser.parse_args()

    input_path = Path(args.input)
    output_path = Path(args.output)

    if not input_path.exists():
        raise FileNotFoundError(
            f"Input file not found: {input_path}"
        )

    print("=" * 70)
    print("Reading CSV")
    print("=" * 70)

    df = pd.read_csv(
        input_path,
        low_memory=False,
    )

    print(f"Rows:    {len(df):,}")
    print(f"Columns: {len(df.columns):,}")

    print("\nValidating source dataset...")
    validate_dataset(df)

    print("Validation passed.")

    # --------------------------------------------------------------
    # Confirm expected size-experiment grain
    # --------------------------------------------------------------
    print("\nRows by N:")

    rows_by_n = (
        df.groupby("N")
        .size()
        .sort_index()
    )

    print(rows_by_n.to_string())

    # --------------------------------------------------------------
    # Measure longest edge-list string
    # --------------------------------------------------------------
    edge_lengths = (
        df["edge_list_json"]
        .astype(str)
        .str.len()
    )

    print(
        f"\nLongest edge_list_json: "
        f"{edge_lengths.max():,} characters"
    )

    # --------------------------------------------------------------
    # Write Parquet
    # --------------------------------------------------------------
    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    print(f"\nWriting: {output_path}")

    df.to_parquet(
        output_path,
        index=False,
        engine="pyarrow",
    )

    # --------------------------------------------------------------
    # Read back and validate again
    # --------------------------------------------------------------
    print("\nReading Parquet back for verification...")

    check = pd.read_parquet(
        output_path,
        engine="pyarrow",
    )

    if len(check) != len(df):
        raise ValueError(
            f"Row-count mismatch after Parquet write: "
            f"{len(df)} -> {len(check)}"
        )

    if list(check.columns) != list(df.columns):
        raise ValueError(
            "Column names/order changed during Parquet conversion."
        )

    # Check that the long JSON survived.
    validate_dataset(check)

    # Exact string-preservation check for edge lists.
    original_edges = df["edge_list_json"].astype(str).tolist()
    parquet_edges = check["edge_list_json"].astype(str).tolist()

    if original_edges != parquet_edges:
        raise ValueError(
            "edge_list_json values changed during Parquet conversion."
        )

    print("\n" + "=" * 70)
    print("SUCCESS")
    print("=" * 70)
    print(f"Output file: {output_path}")
    print(f"Rows:        {len(check):,}")
    print(f"Columns:     {len(check.columns):,}")
    print(
        "Longest edge_list_json preserved: "
        f"{check['edge_list_json'].astype(str).str.len().max():,} characters"
    )

    n100 = check[check["N"].astype(int) == 100]

    print(
        f"N=100 rows verified: {len(n100):,}"
    )

    print("\nYou can now use corrected_results.parquet")
    print("as the input dataset for the N=20/N=50/N=100 analyses.")


if __name__ == "__main__":
    main()